(function () {
  const STORAGE_KEY = '3dlab_lang';
  const SUPPORTED = ['en', 'hy', 'ru'];

  function detectDefaultLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && SUPPORTED.includes(saved)) return saved;
    } catch (e) {}
    const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return SUPPORTED.includes(nav) ? nav : 'en';
  }

  function t(lang, key) {
    return (I18N[lang] && I18N[lang][key]) || (I18N.en && I18N.en[key]) || '';
  }

  function applyLanguage(lang) {
    if (!SUPPORTED.includes(lang)) lang = 'en';

    document.documentElement.setAttribute('lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const value = t(lang, key);
      if (value) el.textContent = value;
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const value = t(lang, key);
      if (value) el.innerHTML = value;
    });

    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
      const spec = el.getAttribute('data-i18n-attr');
      spec.split(';').forEach(pair => {
        const [attr, key] = pair.split(':').map(s => s && s.trim());
        if (!attr || !key) return;
        const value = t(lang, key);
        if (value) el.setAttribute(attr, value);
      });
    });

    const titleEl = document.getElementById('pageTitle');
    if (titleEl) titleEl.textContent = t(lang, 'meta.title');

    const descEl = document.getElementById('metaDescription');
    if (descEl) descEl.setAttribute('content', t(lang, 'meta.description'));

    const ogTitleEl = document.getElementById('metaOgTitle');
    if (ogTitleEl) ogTitleEl.setAttribute('content', t(lang, 'meta.ogTitle'));

    const ogDescEl = document.getElementById('metaOgDescription');
    if (ogDescEl) ogDescEl.setAttribute('content', t(lang, 'meta.ogDescription'));

    const currentLabel = document.getElementById('langCurrent');
    if (currentLabel) currentLabel.textContent = lang.toUpperCase();

    document.querySelectorAll('#langMenu li').forEach(li => {
      li.classList.toggle('is-active', li.getAttribute('data-lang') === lang);
    });

    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  document.addEventListener('DOMContentLoaded', () => {
    const initialLang = detectDefaultLang();
    applyLanguage(initialLang);

    const langSwitch = document.getElementById('langSwitch');
    const langToggle = document.getElementById('langToggle');
    const langMenu = document.getElementById('langMenu');

    if (!langSwitch || !langToggle || !langMenu) return;

    const closeMenu = () => {
      langSwitch.classList.remove('is-open');
      langToggle.setAttribute('aria-expanded', 'false');
    };
    const toggleMenu = () => {
      const open = langSwitch.classList.toggle('is-open');
      langToggle.setAttribute('aria-expanded', String(open));
    };

    langToggle.addEventListener('click', (e) => {
      e.stopPropagation();
      toggleMenu();
    });

    langMenu.querySelectorAll('li[data-lang]').forEach(li => {
      li.addEventListener('click', () => {
        applyLanguage(li.getAttribute('data-lang'));
        closeMenu();
      });
    });

    document.addEventListener('click', (e) => {
      if (!langSwitch.contains(e.target)) closeMenu();
    });

    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape') closeMenu();
    });
  });
})();
